def test_computeLogicals_A1():
    H_X = A1_HX.astype(np.int32)
    H_Z = A1_HZ.astype(np.int32)
    L_X, L_Z = logicals.computeLogicals(H_X, H_Z)
    # H_Z and H_X have the same rank, so must have the same number of logicals and same shape
    _, _, rLX = gf2Algebra.binaryGaussianEliminationOnRows(L_X)
    _, _, rLZ = gf2Algebra.binaryGaussianEliminationOnRows(L_Z)
    assert (rLX == rLZ)
    assert (L_X.shape == L_Z.shape)
    
def test_computeLogicals_4_2_2():
     """
     The [4,2,2] code is generated by S = < XXXX, ZZZZ>
     """
     H_X = np.array([[1,1,1,1]], dtype = np.int32)
     H_Z = np.array([[1,1,1,1]], dtype = np.int32)
     L_X, L_Z = logicals.computeLogicals(H_X, H_Z)
     # H_X and H_Z are identical, so should provide the same logicals (not just the same rank and shape as before)
     assert np.all(L_X == L_Z)
     # NOT A BUG !  The 4,2,2 has 2 logical qubits, so why are we getting 3 logical operators ? 
     # The answer is that we compute a spanning set of logicals, but some might differ only by a stabilizer
     assert L_X.shape == (3, 4)
     

